"""Original acoustic-inspired procedural kit. No recordings, sample packs or network input.
Regenerate with Python + numpy/scipy. Only generated PCM lives in firmware ROM.
"""
from pathlib import Path
import numpy as np
from scipy.signal import butter, sosfilt, resample_poly
SR=44100
rng=np.random.default_rng(174020)
def noise(n,lo,hi):
    return sosfilt(butter(2,[lo,hi],btype='bandpass',fs=SR,output='sos'),rng.standard_normal(n))
def time(seconds):return np.arange(int(SR*seconds))/SR
def mode(t,hz,decay,phase=0):return np.sin(2*np.pi*hz*t+phase)*np.exp(-t/decay)
def finish(x,peak):
    x=sosfilt(butter(1,32,btype='highpass',fs=SR,output='sos'),x)
    x=np.tanh(x*1.3);x[:48]*=np.linspace(0,1,48);x[-300:]*=np.linspace(1,0,300)
    x=resample_poly(x,1,2);x=x/max(abs(x))*peak
    return np.rint(x*32767).astype(np.int16)
kit=[]
t=time(.32);phase=2*np.pi*(49*t+62*.011*(1-np.exp(-t/.011)))
kick=np.sin(phase)*(1-np.exp(-t/.0009))*np.exp(-t/.065)
kick+=.12*mode(t,103,.021)+.045*noise(len(t),900,4600)*np.exp(-t/.005)
kit.append(('kick',finish(kick,.85)))
t=time(.30)
body=.48*mode(t,184,.032)+.21*mode(t,337,.021)+.09*mode(t,512,.015)
wire=noise(len(t),1100,8600)
wire2=noise(len(t),2200,6900)
snare=body+.74*wire*(1-np.exp(-t/.0011))*np.exp(-t/.043)+.12*wire2*np.exp(-((t-.014)/.006)**2)
snare+=.045*noise(len(t),320,1200)*np.exp(-t/.06)
kit.append(('snare',finish(snare,.78)))
t=time(.105);ghost=.46*mode(t,205,.022)+.34*noise(len(t),1500,7400)*(1-np.exp(-t/.0015))*np.exp(-t/.025)
kit.append(('ghost',finish(ghost,.58)))
for name,dur,decay,peak in [('hat',.11,.014,.40),('open',.36,.077,.43),('ride',.95,.23,.48)]:
 t=time(dur);wash=noise(len(t),4300,10000)
 metal=sum(mode(t,f,decay*.8,rng.random()*6.28) for f in [3417,4741,6187,7933,9619])/5
 x=(wash*.8+metal*.15)*(1-np.exp(-t/.0005))*np.exp(-t/decay)
 if name=='ride':x+=.08*mode(t,2731,.055)+.12*noise(len(t),2600,6400)*np.exp(-t/.12)
 kit.append((name,finish(x,peak)))
t=time(.32);ph=2*np.pi*(115*t+28*.014*(1-np.exp(-t/.014)))
tom=np.sin(ph)*np.exp(-t/.067)+.25*mode(t,180,.035)+.025*noise(len(t),500,3500)*np.exp(-t/.02)
kit.append(('tom',finish(tom,.65)))
t=time(.12);perc=.55*mode(t,920,.012)+.24*mode(t,1377,.008)+.15*noise(len(t),1800,6000)*np.exp(-t/.011)
kit.append(('perc',finish(perc,.43)))
root=Path(__file__).resolve().parents[1]
lines=['/* SPDX-License-Identifier: GPL-3.0-only',' * Generated by tools/design_drums.py. Original synthesized PCM, 22050 Hz. */','#ifndef B174_DRUM_ROM_H','#define B174_DRUM_ROM_H']
for name,data in kit:
 lines.append('static const int16_t b174_rom_'+name+'[] = {')
 for i in range(0,len(data),24):lines.append(','.join(map(str,data[i:i+24]))+',')
 lines.append('};')
lines.append('static const int16_t *const b174_rom[8] = {'+','.join('b174_rom_'+n for n,_ in kit)+'};')
lines.append('static const uint32_t b174_rom_len[8] = {'+','.join(str(len(a)) for _,a in kit)+'};')
lines+=['#endif','']
(root/'core/drum_rom.h').write_text('\n'.join(lines))
sine=np.rint(np.sin(np.arange(1025)*2*np.pi/1024)*32767).astype(int)
(root/'core/sine_rom.h').write_text('/* SPDX-License-Identifier: GPL-3.0-only */\nstatic const int16_t b174_sine_rom[1025] = {\n'+','.join(map(str,sine))+'\n};\n')
print('drum ROM:',sum(a.nbytes for _,a in kit),'bytes; synthesized only')

with (root/'core/sine_rom.h').open('a') as f:
    f.write('static const uint32_t b174_midi_inc[108] = {'+','.join(str(round(440*2**((n-69)/12)*2**32/44100))+'u' for n in range(108))+'};\n')
