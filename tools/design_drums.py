"""Authentic Roland TR-808 analog drum synthesis model.
Generates pristine 22050 Hz int16 ROM tables for core/drum_rom.h and sine_rom.h.
"""
from pathlib import Path
import numpy as np
from scipy.signal import butter, sosfilt, resample_poly

SR = 44100
rng = np.random.default_rng(808174)

def time(seconds):
    return np.arange(int(SR * seconds)) / SR

def noise(n, lo, hi):
    sos = butter(2, [lo, hi], btype='bandpass', fs=SR, output='sos')
    return sosfilt(sos, rng.standard_normal(n))

def finish(x, peak):
    # Highpass DC blocker
    hp_sos = butter(1, 25, btype='highpass', fs=SR, output='sos')
    x = sosfilt(hp_sos, x)
    # Warm analog soft saturation (Roland style diode/transistor curve)
    x = np.tanh(x * 1.25)
    # Anti-alias lowpass before 2x decimation to 22.05 kHz
    lp_sos = butter(4, 9800, btype='lowpass', fs=SR, output='sos')
    x = sosfilt(lp_sos, x)
    # Smooth fade-in and fade-out to prevent clicks
    x[:32] *= np.linspace(0, 1, 32)
    x[-128:] *= np.linspace(1, 0, 128)
    # Resample to 22050 Hz PCM
    x = resample_poly(x, 1, 2)
    mx = np.max(np.abs(x))
    if mx > 0:
        x = (x / mx) * peak
    return np.rint(x * 32767).astype(np.int16)

kit = []

# --- 1. KICK (TR-808 Bass Drum) ---
# Deep 808 sine pitch glide from ~120Hz down to 49Hz + tight transient attack pulse
t = time(0.42)
freq_env = 49.0 + (120.0 - 49.0) * np.exp(-t / 0.012) + 25.0 * np.exp(-t / 0.003)
phase = 2 * np.pi * np.cumsum(freq_env) / SR
body = np.sin(phase) * np.exp(-t / 0.085)
# Transient attack click / punch
click = noise(len(t), 800, 4500) * np.exp(-t / 0.004) * 0.25
# Sub tone decay
sub = np.sin(2 * np.pi * 49.0 * t) * np.exp(-t / 0.18) * 0.35
kick_raw = body + click + sub
kit.append(('kick', finish(kick_raw, 0.88)))

# --- 2. SNARE (TR-808 Snare Drum) ---
# Dual bridged-T shell resonance (~180Hz & ~330Hz) + filtered snappy noise
t = time(0.32)
shell1 = np.sin(2 * np.pi * 182.0 * t) * np.exp(-t / 0.035) * 0.45
shell2 = np.sin(2 * np.pi * 335.0 * t) * np.exp(-t / 0.022) * 0.25
snappy_noise = noise(len(t), 1800, 7500) * np.exp(-t / 0.075) * 0.75
snare_raw = shell1 + shell2 + snappy_noise
kit.append(('snare', finish(snare_raw, 0.82)))

# --- 3. GHOST (TR-808 Soft Snare / Ghost Note) ---
t = time(0.12)
g_shell = np.sin(2 * np.pi * 180.0 * t) * np.exp(-t / 0.025) * 0.35
g_noise = noise(len(t), 2000, 6500) * np.exp(-t / 0.035) * 0.40
ghost_raw = g_shell + g_noise
kit.append(('ghost', finish(ghost_raw, 0.55)))

# --- 4, 5, 6. HI-HATS & RIDE (TR-808 6-Oscillator Metallic Sound) ---
# 808 Cymbal/Hat metallic modes: 207, 307, 370, 524, 544, 807 Hz square waves
def gen_808_metallic(dur, decay, hp_freq, peak):
    t = time(dur)
    sq_freqs = [207.0, 307.0, 370.0, 524.0, 544.0, 807.0]
    metal_sum = np.zeros_like(t)
    for f in sq_freqs:
        sq = np.sign(np.sin(2 * np.pi * f * t))
        metal_sum += sq
    metal_sum /= len(sq_freqs)
    # Pass through 808 high-pass filter
    sos = butter(2, hp_freq, btype='highpass', fs=SR, output='sos')
    filtered = sosfilt(sos, metal_sum)
    env = (1 - np.exp(-t / 0.0005)) * np.exp(-t / decay)
    return finish(filtered * env, peak)

kit.append(('hat', gen_808_metallic(0.12, 0.022, 6500, 0.45)))
kit.append(('open', gen_808_metallic(0.40, 0.110, 5500, 0.50)))
kit.append(('ride', gen_808_metallic(0.85, 0.280, 4200, 0.52)))

# --- 7. TOM (TR-808 Low/Mid Tom) ---
# Bridged-T sine oscillation around ~115Hz with fast pitch drop
t = time(0.35)
f_env = 115.0 + 35.0 * np.exp(-t / 0.015)
ph = 2 * np.pi * np.cumsum(f_env) / SR
tom_raw = np.sin(ph) * np.exp(-t / 0.085) + 0.15 * noise(len(t), 600, 2500) * np.exp(-t / 0.012)
kit.append(('tom', finish(tom_raw, 0.72)))

# --- 8. PERC (TR-808 Rimshot / Handclap / Cowbell Style Accent) ---
# Rimshot twin pulse ring (~1700Hz + ~2800Hz)
t = time(0.14)
r1 = np.sin(2 * np.pi * 1720.0 * t) * np.exp(-t / 0.012) * 0.55
r2 = np.sin(2 * np.pi * 2780.0 * t) * np.exp(-t / 0.008) * 0.35
perc_raw = r1 + r2
kit.append(('perc', finish(perc_raw, 0.52)))

# Generate drum_rom.h
root = Path(__file__).resolve().parents[1]
lines = [
    '/* SPDX-License-Identifier: GPL-3.0-only',
    ' * Generated by tools/design_drums.py. Authentic Roland TR-808 synthesized PCM, 22050 Hz. */',
    '#ifndef B174_DRUM_ROM_H',
    '#define B174_DRUM_ROM_H'
]
for name, data in kit:
    lines.append(f'static const int16_t b174_rom_{name}[] = {{')
    for i in range(0, len(data), 24):
        lines.append(','.join(map(str, data[i:i+24])) + ',')
    lines.append('};')

lines.append('static const int16_t *const b174_rom[8] = {' + ','.join('b174_rom_' + n for n, _ in kit) + '};')
lines.append('static const uint32_t b174_rom_len[8] = {' + ','.join(str(len(a)) for _, a in kit) + '};')
lines += ['#endif', '']
(root / 'core/drum_rom.h').write_text('\n'.join(lines))

# Generate sine_rom.h with high-precision 1024-step sine table and 32-bit MIDI phase increments
sine = np.rint(np.sin(np.arange(1025) * 2 * np.pi / 1024) * 32767).astype(int)
sine_lines = [
    '/* SPDX-License-Identifier: GPL-3.0-only */',
    '#ifndef B174_SINE_ROM_H',
    '#define B174_SINE_ROM_H',
    'static const int16_t b174_sine_rom[1025] = {',
    ','.join(map(str, sine)),
    '};'
]
sine_lines.append('static const uint32_t b174_midi_inc[108] = {' + ','.join(str(round(440 * 2**((n - 69) / 12) * 2**32 / 44100)) + 'u' for n in range(108)) + '};')
sine_lines += ['#endif', '']
(root / 'core/sine_rom.h').write_text('\n'.join(sine_lines))

print('Roland TR-808 drum ROM regenerated successfully!')
